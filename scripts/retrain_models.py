def load_real_data(name: str, cfg: dict) -> tuple[np.ndarray, np.ndarray, int]:
    """Load Tier 1 (Foundry) + Tier 2 (scraped) data and apply feature transform."""
    rows_X, rows_y = [], []

    for src_dir in [FOUNDRY_DIR, REAL_DIR]:
        for row in load_csv(src_dir / f"{name}.csv"):
            try:
                x = cfg["transform"](row)
                y = np.log(float(row["price_inr"]))
                rows_X.append(x)
                rows_y.append(y)
            except Exception:
                pass

    if not rows_X:
        return np.empty((0, 0)), np.empty(0), 0
    return np.array(rows_X), np.array(rows_y), len(rows_X)


def blend(name: str, cfg: dict) -> tuple[np.ndarray, np.ndarray, int]:
    X_real, y_real, n_real = load_real_data(name, cfg)

    if n_real >= BLEND_ONLY_REAL:
        log.info("  %s: %d real rows — using real data only", name, n_real)
        return X_real, y_real, n_real

    # How many synthetic rows to add
    if n_real >= BLEND_HALF:
        n_synth = n_real            # 50/50
        log.info("  %s: %d real rows — blending 50/50 with synthetic", name, n_real)
    else:
        n_synth = max(300, n_real * 7 // 3)  # ~70% synthetic
        log.info("  %s: %d real rows — blending 30/70 real/synthetic", name, n_real)

    X_s, y_s = cfg["synth_fn"](n_synth)

    if n_real == 0:
        return X_s, y_s, 0

    X = np.vstack([X_real, X_s])
    y = np.concatenate([y_real, y_s])
    return X, y, n_real


